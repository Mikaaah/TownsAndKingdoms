const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs');
(async()=>{
 const browser=await chromium.launch({headless:true,args:['--no-sandbox'],executablePath:process.env.CHROMIUM_PATH||(fs.existsSync('/usr/bin/chromium')?'/usr/bin/chromium':undefined)});
 const context=await browser.newContext({viewport:{width:1440,height:1100}});
 const page=await context.newPage(),errors=[],assetFailures=[];
 page.on('pageerror',error=>errors.push(error.message));
 page.on('response',response=>{if(response.url().includes('/media/skills/')&&response.status()>=400)assetFailures.push(response.url());});
 const url=process.env.PORTAL_URL||'http://127.0.0.1:4321/TownsAndKingdoms/skills/';
 await page.goto(url);await page.waitForSelector('[data-skill-planner][data-skill-ready="true"] .sp-node');
 assert.equal(await page.locator('.sp-node').count(),588);assert.equal(await page.locator('.sp-connection').count(),669);
 assert.equal(await page.locator('[data-skill-spent]').textContent(),'0');
 assert.equal(await page.locator('[data-skill-available]').textContent(),'175');
 await page.locator('[data-node-id="alchemist_class"]').click();
 await page.locator('[data-node-id="alchemist_crafting_1"]').click();
 await page.locator('[data-node-id="miner_class"]').click();
 assert.equal(await page.locator('[data-skill-spent]').textContent(),'3');
 await page.locator('[data-node-id="alchemist_class"]').click({button:'right'});
 assert.equal(await page.locator('[data-skill-spent]').textContent(),'1');
 await page.locator('[data-skill-undo]').click();assert.equal(await page.locator('[data-skill-spent]').textContent(),'3');
 await page.locator('[data-skill-reset]').click();
 const level=page.locator('[data-skill-level]');await level.fill('50');await level.press('Tab');
 assert.equal(await page.locator('[data-skill-available]').textContent(),'87');
 await level.fill('100');await level.press('Tab');
 await page.locator('[data-skill-search]').fill('Potion Longevity');
 await page.locator('[data-skill-results] button').first().click();
 assert.equal(await page.locator('[data-skill-detail-title]').textContent(),'Potion Longevity');
 const camera=page.locator('[data-skill-camera]'),before=await camera.getAttribute('transform');
 await page.locator('[data-skill-zoom="in"]').click();await page.waitForTimeout(50);
 assert.notEqual(await camera.getAttribute('transform'),before);
 await page.locator('[data-node-id="alchemist_class"]').press('Enter');
 assert.equal(await page.locator('[data-skill-spent]').textContent(),'1');
 await page.locator('[data-skill-share]').click();
 const link=await page.locator('[data-skill-share-link]').inputValue();assert(link.includes('build='));
 const fresh=await browser.newContext({viewport:{width:1200,height:1000}}),restored=await fresh.newPage();
 await restored.goto(link);await restored.waitForSelector('.sp-node.is-allocated');
 assert.equal(await restored.locator('[data-skill-spent]').textContent(),'1');
 await page.setViewportSize({width:390,height:844});await page.locator('[data-skill-fit]').click();
 assert.equal(await page.locator('.sp-node').count(),588);
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+1));
 assert.equal(errors.length,0,errors.join('\n'));assert.equal(assetFailures.length,0,assetFailures.join('\n'));
 await browser.close();console.log(JSON.stringify({passed:true,nodes:588,links:669,checks:['allocation','multiple roots','dependent refunds','undo','reset','level budget','skill search','zoom','keyboard allocation','share reload','mobile width'],javascript_errors:errors,missing_icons:assetFailures}));
})().catch(error=>{console.error(error);process.exitCode=1;});
